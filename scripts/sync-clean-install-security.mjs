import fs from 'node:fs';
const clean=new URL('../supabase/V4_0_CLEAN_INSTALL.sql',import.meta.url);
const upgrade=new URL('../supabase/V4_0_20_SECURITY_HARDENING.sql',import.meta.url);
const marker='-- BEGIN GENERATED SECURITY HARDENING';
let original=fs.readFileSync(clean,'utf8').split(marker)[0];
original=original.replace(/\ncommit;\nnotify pgrst,'reload schema';\s*$/,'\n');
const security=fs.readFileSync(upgrade,'utf8').replace(/^begin;$/m,'').replace(/^commit;$/m,'').replace(/^notify pgrst,'reload schema';$/m,'');
const output=original+marker+' — generated by scripts/sync-clean-install-security.mjs\n'+security+"\ncommit;\nnotify pgrst,'reload schema';\n";
if(process.argv.includes('--check')){
  if(fs.readFileSync(clean,'utf8')!==output)throw new Error('Clean-install security is stale. Run node scripts/sync-clean-install-security.mjs.');
}else fs.writeFileSync(clean,output);
